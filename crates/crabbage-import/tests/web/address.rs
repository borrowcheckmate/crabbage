use crabbage_import::web::is_public;

#[test]
fn public_addresses_are_allowed() {
    for ip in [
        "93.184.216.34",
        "2606:4700::1",
        "8.8.8.8",
        "172.32.0.1",
        "100.128.0.1",
        "::ffff:93.184.216.34",
    ] {
        assert!(is_public(ip.parse().expect(ip)), "{ip}");
    }
}

#[test]
fn private_and_special_addresses_are_refused() {
    for ip in [
        "127.0.0.1",
        "0.0.0.0",
        "0.1.2.3",
        "10.0.0.1",
        "172.16.0.1",
        "172.31.255.255",
        "192.168.1.1",
        "169.254.169.254",
        "100.64.0.1",
        "100.127.255.255",
        "255.255.255.255",
        "224.0.0.1",
        "192.0.2.1",
        "198.51.100.7",
        "203.0.113.9",
        "::1",
        "::",
        "fe80::1",
        "fc00::1",
        "fd12:3456::1",
        "ff02::1",
        "2001:db8::1",
        "::ffff:127.0.0.1",
        "::ffff:10.0.0.1",
        "::ffff:100.64.0.1",
    ] {
        assert!(!is_public(ip.parse().expect(ip)), "{ip}");
    }
}
